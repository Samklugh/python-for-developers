#the for loop is used for iterating over a sequence (like a list, tuple, dictionary, set, or string)

#the sameple is for "iterator varaible" in a list. the iterator variable takes the value of the item inside the sequence on each iteration. the loop continues until all items in the sequence have been processed. then the loop ends. the iterator variable is only accessible inside the loop body.

cities = ["Provo", "Orem", "Salt Lake City", "Lehi"]
